changed = []
for level in ('intermediate', 'advanced'):
    path = Path(f'content/{level}-readings/books.json')
    books = json.loads(path.read_text(encoding='utf-8'))
    for book in books:
        pages = []
        if book['genre'] == 'poem':
            continue
        for number, page in enumerate(book['pages'], 1):
            original = page['translation']
            for old, new in replacements.items():
                page['translation'] = page['translation'].replace(old, new)
            if original != page['translation']:
                pages.append(number)
        if pages:
            changed.append({'id': book['id'], 'pages': pages})
    path.write_text(json.dumps(books, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
approval_path = Path('content/picture-book-approval.json')
approval = json.loads(approval_path.read_text(encoding='utf-8'))
for item in changed:
    level = item['id'].split('-')[0]
    book = next(b for b in json.loads(Path(f'content/{level}-readings/books.json').read_text(encoding='utf-8')) if b['id'] == item['id'])
    entry = next(b for b in approval['books'] if b['id'] == item['id'])
    entry['contentSha256'] = hashlib.sha256(json.dumps(book, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()
    entry['translationReview'] = {'date': '2026-10-21', 'pages': item['pages'], 'evidence': 'content/translation-review-2026-10-21.md'}
approval_path.write_text(json.dumps(approval, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
